#!/usr/bin/env python3
"""Graph builder: 9-axis taste vector + seed (+ emotion) -> a real Infinite patch with branches, motion and riso finish.

Replaces the single fixed chain in executor.build. Each piece is two branches from different families joined by a Blend,
then a riso finish (halftone / dither / posterize), grain, vignette. Colours come from the brand palette, never from raw hue.
Families: field (Noise, warped), mandala (Shape -> kaleidoscope -> Trails), organism (Reaction Diffusion).
Image wires only, so every cable is legal (graph_rules.json: image -> image). Enum params take the engine's own names.
"""
import colorsys, random

BRAND = {  # brand/brand_book.html tokens
    'ink': '#0A0618', 'deep': '#140B52', 'indigo': '#2A1A9E', 'blue': '#2E3BDB', 'volt': '#3D5BFF', 'violet': '#5A22B8',
    'lav': '#B8B5F0', 'mag': '#E0368F', 'red': '#FF2E4A', 'gold': '#F6E27A', 'cream': '#F4EFA1', 'white': '#FBF8E8',
}
# 70/20/10: ink ground, volt + lavender dominant, accents rare. (ground, main, second, accent) per hue slot
PALETTES = [
    ('ink', 'volt', 'lav', 'cream'), ('deep', 'lav', 'volt', 'gold'), ('ink', 'violet', 'lav', 'mag'),
    ('indigo', 'cream', 'volt', 'mag'), ('ink', 'lav', 'blue', 'gold'), ('deep', 'volt', 'cream', 'red'),
]
FAMILIES = ['field', 'mandala', 'organism']
BLENDS = ['Screen', 'Add', 'Overlay', 'Difference', 'Exclusion', 'Soft Light', 'Lighten']


def lerp(a, b, t): return a + (b - a) * t
def clamp(x, a=0.0, b=1.0): return max(a, min(b, x))


def rgb(name):
    h = BRAND[name].lstrip('#')
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def fmt(c): return ' '.join(f'{x:.3f}' for x in c)


class G:
    def __init__(self):
        self.lines, self.tail, self.n = ['infinite-patch 1', '# generated by tools/art/graph_builder.py'], [], 0

    def node(self, cat, typ, params=(), nid=None):
        self.n += 1
        nid = nid or f'n{self.n}'
        self.lines += [f'node {self.n} {cat} {typ}', f'  id {nid}', *[f'  {p}' for p in params], 'end']
        return nid

    def cable(self, dst, slot, src): self.tail.append(f'cable {dst} {slot} {src}')
    def expr(self, nid, param, e): self.tail.append(f'expr {nid} {param} {e}')

    def chain(self, src, *steps):
        """steps: (category, type, params[, expr_param, expr]); returns last node id."""
        for st in steps:
            nid = self.node(st[0], st[1], st[2])
            self.cable(nid, 0, src)
            if len(st) > 3: self.expr(nid, st[3], st[4])
            src = nid
        return src

    def text(self): return '\n'.join(self.lines + self.tail) + '\n'


def branch(g, family, a, pal, r, tag):
    ground, main, second, accent = (rgb(x) for x in pal)
    spd = lerp(0.1, 1.2, a['speed'])
    if family == 'field':
        nt = r.choice(['fBm', 'Ridged', 'Voronoi', 'Simplex fBm', 'Worley Edges'])
        src = g.node('Source', 'Noise', [f'i noiseType {nt}', f'f scale {lerp(2, 14, a["size"]):.2f}',
                                         f'f octaves {round(lerp(2, 6, a["noise"]))}', f'f warp {lerp(0.2, 1.4, a["amount"]):.2f}',
                                         f'f speed {spd * 0.3:.3f}', f'f contrast {lerp(1.1, 2.0, a["contrast"]):.2f}',
                                         f'f seed {r.uniform(0, 100):.2f}', f'c lowColor {fmt(ground)}', f'c highColor {fmt(main)}'], f'{tag}src')
        warp = r.choice([
            ('Effects', 'liquify', [f'f uAmount {lerp(0.3, 1.2, a["amount"]):.2f}', f'f uScale {lerp(2, 9, a["size"]):.2f}'], 'uSpeed', f'{lerp(0.1, 0.8, a["speed"]):.2f}'),
            ('Effects', 'twirl', [f'f uAngle {lerp(1, 4, a["amount"]):.2f}', 'f uRadius 0.7'], 'uAngle', f'{lerp(1, 4, a["amount"]):.2f} * sin(t * {spd:.2f})'),
            ('Effects', 'ripple', [f'f uAmplitude {lerp(0.2, 1.1, a["amount"]):.2f}', f'f uWavelength {lerp(4, 20, a["size"]):.1f}'], 'uPhase', f't * {spd * 3:.2f}'),
        ])
        return g.chain(src, warp)
    if family == 'mandala':
        shape = r.choice(['Star', 'Gear', 'Heart', 'Blob', 'Polygon', 'Teardrop', 'Crescent', 'Cross'])
        sz = lerp(0.05, 0.16, a['size'])
        src = g.node('Source', 'Shape', [f'i shapeType {shape}', f'f sizeX {sz:.3f}', f'f sizeY {sz * lerp(0.6, 1, a["amount"]):.3f}',
                                         f'f posX {r.uniform(0.55, 0.8):.2f}', f'f posY {r.uniform(0.2, 0.8):.2f}', f'f rotation {r.uniform(0, 90):.0f}',
                                         f'f feather {lerp(0, 0.08, a["softness"]):.3f}', f'c fillColor {fmt(main)}', f'c bgColor {fmt(ground)}', 'f bgOpacity 1'], f'{tag}src')
        return g.chain(src,
                       ('Effects', 'kaleidoscope', [f'f uSegments {round(lerp(3, 16, a["symmetry"]))}', f'f uZoom {lerp(0.8, 1.6, a["amount"]):.2f}'],
                        'uRotation', f't * {spd:.3f}'),
                       ('Compositing', 'Trails', [f'f decay {lerp(0.6, 0.82, 1 - a["softness"]):.3f}', f'f zoom {lerp(0.99, 1.02, a["amount"]):.3f}',
                                                  f'f rotate {lerp(-1.5, 1.5, r.random()):.2f}', 'i blendMode Max'], 'rotate', f'{lerp(0.3, 1.5, a["speed"]):.2f} * sin(t * 0.5)'))
    # organism
    seed = g.node('Source', 'Noise', [f'i noiseType {r.choice(["Voronoi", "Perlin fBm", "Simplex"])}', f'f scale {lerp(3, 10, a["size"]):.1f}',
                                      f'f seed {r.uniform(0, 100):.2f}', f'c lowColor {fmt(ground)}', f'c highColor {fmt(accent)}'], f'{tag}seed')
    preset = r.choice(['Coral', 'Mitosis', 'Maze', 'Spots', 'Worms'])
    return g.chain(seed, ('Compositing', 'Reaction Diffusion', [f'i preset {preset}', 'f stepsPerFrame 32',
                                                              f'f sourceInfluence {lerp(0.8, 1.0, a["noise"]):.2f}', f'c lowColor {fmt(ground)}', f'c highColor {fmt(second)}']))


def build_graph(axes, seed=0, mood=None):
    """mood: optional dict of emotion coords (valence, arousal, stress, energy, dominance 0..1) that also pick structure."""
    a = {k: clamp(float(axes.get(k, 0.5))) for k in ('brightness', 'hue', 'contrast', 'speed', 'noise', 'softness', 'symmetry', 'amount', 'size')}
    mood = mood or {}
    r = random.Random(seed)
    pal = PALETTES[int(a['hue'] * 5.99)]
    # structure follows feeling: stress -> broken/glitchy, calm -> trails and growth, energy -> geometry
    stress, arousal = mood.get('stress', a['noise']), mood.get('arousal', a['speed'])
    fam_w = {'field': 1 + 2 * stress, 'mandala': 1 + 2 * a['symmetry'] + arousal, 'organism': 1 + 2 * (1 - stress) * a['softness']}
    fams = r.choices(FAMILIES, [fam_w[f] for f in FAMILIES], k=1)
    other = [f for f in FAMILIES if f != fams[0]]
    fams.append(r.choice(other))
    g = G()
    g.lines.append('# axes ' + ' '.join(f'{k}={v:.2f}' for k, v in a.items()) + f' | palette {"/".join(pal)} | {fams[0]}+{fams[1]}')
    A = branch(g, fams[0], a, pal, r, 'a')
    B = branch(g, fams[1], a, pal, r, 'b')
    mode = BLENDS[int(clamp(a['contrast'] * 0.5 + r.random() * 0.5) * 6.99)]
    top = g.node('Compositing', 'Blend', [f'i mode {mode}', f'f mix {lerp(0.45, 0.9, a["amount"]):.2f}'], 'join')
    g.cable(top, 0, A); g.cable(top, 1, B)
    steps = []
    # riso finish: halftone when it is crisp and grainy, dither when soft, posterize otherwise
    if a['noise'] > 0.55 and a['contrast'] > 0.5:
        steps.append(('Effects', 'halftone', [f'f uScale {lerp(50, 130, a["size"]):.0f}', f'f uAngle {r.uniform(0.2, 1.2):.2f}']))
    elif a['softness'] > 0.6:
        steps.append(('Compositing', 'dither', [f'f uLevels {round(lerp(3, 8, a["contrast"]))}', 'f uMix 0.8']))
    else:
        steps.append(('Compositing', 'posterize', [f'f uLevels {round(lerp(4, 9, a["contrast"]))}']))
    if stress > 0.6:
        steps.append(('Effects', 'glitch', [f'f uAmount {lerp(0.1, 0.5, stress):.2f}', f'f uSeed {r.uniform(0, 100):.1f}'], 'uSpeed', f'{lerp(0.5, 2, arousal):.2f}'))
    steps += [('Effects', 'bloom', [f'f uIntensity {lerp(0.2, 0.7, a["brightness"]):.2f}', 'f uThreshold 0.55']),
              ('Effects', 'addnoise', [f'f uAmount {lerp(0.05, 0.25, a["noise"]):.2f}']),
              ('Effects', 'vignette', []),
              ('Compositing', 'color adjustments', [f'f uContrast {lerp(-0.1, 0.5, a["contrast"]):.2f}', f'f uBrightness {lerp(-0.2, 0.15, a["brightness"]):.2f}'])]
    last = g.chain(top, *steps)
    out = g.node('Utility', 'Output', [], 'out')
    g.cable(out, 0, last)
    return g.text(), {'families': fams, 'palette': pal, 'blend': mode}


if __name__ == '__main__':
    import json, sys
    ax = json.loads(sys.argv[1]) if len(sys.argv) > 1 else {}
    print(build_graph(ax, int(sys.argv[2]) if len(sys.argv) > 2 else 0)[0])
