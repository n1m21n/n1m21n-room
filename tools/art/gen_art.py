#!/usr/bin/env python3
"""Bake taste.json + param_semantics.json + emotion prototypes into site/src/sim/data/art.gen.js."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, "..", "..")
T = json.load(open(os.path.join(HERE, "taste.json"))); S = json.load(open(os.path.join(HERE, "param_semantics.json")))["axes"]
EM = json.load(open(os.path.join(ROOT, "tools/emotions/emotions.json")))["emotions"]
protos = {n: e.get("prototype") or e.get("proto") for n, e in EM.items()}
out = os.path.join(ROOT, "site/src/sim/data/art.gen.js")
with open(out, "w") as f:
    f.write("// GENERATED by tools/art/gen_art.py from taste.json, param_semantics.json, emotions.json\n")
    f.write("export const TASTE = " + json.dumps(T, indent=1) + ";\n")
    f.write("export const AXIS_EMOTION = " + json.dumps({k: v for k, v in S.items() if v and k in T["guideline"]["axes"]}, indent=1) + ";\n")
print("wrote", out, [n for n, p in protos.items() if not p][:3])
