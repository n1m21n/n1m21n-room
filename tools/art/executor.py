#!/usr/bin/env python3
"""Art executor: 9-axis taste vector -> Infinite patch (.inf) -> validate / frame / render.

Axes (all 0..1): brightness hue contrast speed noise softness symmetry amount size.
Chain: Shape -> kaleidoscope -> gaussianblur -> addnoise -> bloom -> gradientmap
       -> color adjustments -> Output.   Speed drives rotation by expression.

  executor.py --axes '{"hue":.7,"symmetry":.6}' --out piece.inf [--validate] [--frame DIR] [--render FILE]
  executor.py --seed 7 ...        (random axes, reproducible)
"""
import argparse, colorsys, json, os, random, subprocess, sys

CLI = os.path.expanduser('~/Infinite/repo/build/Infinite.app/Contents/MacOS/Infinite')
AXES = ['brightness', 'hue', 'contrast', 'speed', 'noise', 'softness', 'symmetry', 'amount', 'size']
SHAPES = ['Circle', 'Star', 'Blob', 'Ring']


def lerp(a, b, t):
    return a + (b - a) * t


def clamp(x):
    return max(0.0, min(1.0, x))


def build_legacy(axes, seed=0):
    a = {k: clamp(float(axes.get(k, 0.5))) for k in AXES}
    r = random.Random(seed)
    shape = SHAPES[int(a['amount'] * 3.99)] if 'shape' not in axes else axes['shape']
    # colour: dark ground, hue-driven highlight; brightness lifts the shadow colour
    hl = colorsys.hsv_to_rgb(a['hue'], lerp(0.25, 0.65, a['contrast']), 1.0)
    sh = colorsys.hsv_to_rgb((a['hue'] + 0.55) % 1, 0.6, lerp(0.02, 0.16, a['brightness']))
    L = ['infinite-patch 1', '# generated by tools/art/executor.py from a taste vector']
    L += [f'# axes ' + ' '.join(f'{k}={a[k]:.2f}' for k in AXES)]

    def node(n, cat, typ, nid, lines=()):
        L.extend([f'node {n} {cat} {typ}', f'  id {nid}', *[f'  {x}' for x in lines], 'end'])

    sz = lerp(0.1, 0.4, a['size'])
    node(1, 'Source', 'Shape', 'shape', [f'f sizeX {sz:.3f}', f'f sizeY {sz * lerp(0.7, 1, a["amount"]):.3f}',
                                         f'i shapeType {shape}', f'f feather {lerp(0.0, 0.1, a["softness"]):.3f}'])
    node(2, 'Effects', 'kaleidoscope', 'kal', [f'f uSegments {round(lerp(2, 24, a["symmetry"]))}',
                                                f'f uZoom {lerp(0.9, 1.4, a["amount"]):.3f}'])
    node(3, 'Effects', 'gaussianblur', 'blur', [f'f uRadius {lerp(3, 10, a["softness"]):.3f}'])
    node(4, 'Effects', 'addnoise', 'noise', [f'f uAmount {lerp(0, 0.5, a["noise"]):.3f}'])
    node(5, 'Effects', 'bloom', 'bloom', [f'f uIntensity {lerp(0.1, 0.7, a["brightness"]):.3f}'])
    node(6, 'Compositing', 'gradientmap', 'grad', [f'c uShadowColor {sh[0]:.3f} {sh[1]:.3f} {sh[2]:.3f}',
                                                    f'c uHighlightColor {hl[0]:.3f} {hl[1]:.3f} {hl[2]:.3f}'])
    node(7, 'Compositing', 'color adjustments', 'adj', [f'f uContrast {lerp(-0.4, 0.6, a["contrast"]):.3f}',
                                                         f'f uBrightness {lerp(-0.3, 0.3, a["brightness"]):.3f}'])
    node(8, 'Utility', 'Output', 'out')
    L += ['cable kal 0 shape', 'cable blur 0 kal', 'cable noise 0 blur', 'cable bloom 0 noise',
          'cable grad 0 bloom', 'cable adj 0 grad', 'cable out 0 adj']
    spd = lerp(0.1, 1.6, a['speed'])
    L += [f'expr kal uRotation t * {spd:.3f}']
    return '\n'.join(L) + '\n'


def build(axes, seed=0, mood=None):
    """Graph builder (branches, motion, brand palette, riso finish). build_legacy is the old fixed 8-node chain."""
    import graph_builder
    return graph_builder.build_graph(axes, seed, mood)[0]


def run(*args):
    p = subprocess.run([CLI, *args], capture_output=True, text=True)
    return p.returncode, (p.stdout + p.stderr).strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--axes', default='{}')
    ap.add_argument('--seed', type=int)
    ap.add_argument('--out', required=True)
    ap.add_argument('--validate', action='store_true')
    ap.add_argument('--frame')
    ap.add_argument('--times', default='0,1,2')
    ap.add_argument('--render')
    o = ap.parse_args()
    axes = json.loads(o.axes)
    if o.seed is not None:
        r = random.Random(o.seed)
        axes = {k: r.random() for k in AXES} | axes
    open(o.out, 'w').write(build(axes, o.seed or 0))
    if o.validate:
        rc, msg = run('--validate', o.out)
        print(msg)
        if rc:
            sys.exit(rc)
    if o.frame:
        os.makedirs(o.frame, exist_ok=True)
        rc, msg = run('--frame', o.out, o.times, o.frame, '--contact-sheet', os.path.join(o.frame, 'sheet.png'))
        print(msg)
        if rc:
            sys.exit(rc)
    if o.render:
        rc, msg = run('--render', o.out, o.render)
        print(msg)
        sys.exit(rc)


if __name__ == '__main__':
    main()
